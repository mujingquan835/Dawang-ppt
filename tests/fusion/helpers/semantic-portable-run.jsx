import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {chromium} from '../../../skills/dawang-ppt/project/node_modules/playwright-core/index.mjs';
import {semanticFixture} from './semantic-fixture.mjs';
import {createAuthoredProject} from '../../../skills/dawang-ppt/project/src/fusion/authoring/create-project.mjs';
import {renderProject} from '../../../skills/dawang-ppt/project/src/fusion/scene/render-project.jsx';
import {saveProject,loadProject} from '../../../skills/dawang-ppt/project/src/fusion/project/store.mjs';
import {createFusionServer} from '../../../skills/dawang-ppt/project/scripts/fusion-preview.jsx';
import {extractPortableProject,validatePortableHtml} from '../../../skills/dawang-ppt/project/src/fusion/portable/html.mjs';
import {measureProject} from '../../../skills/dawang-ppt/project/src/fusion/qa/measure.mjs';
import {checkCoverage} from '../../../skills/dawang-ppt/project/src/fusion/qa/coverage.mjs';
const dir=process.argv[2];fs.mkdirSync(dir,{recursive:true});
const file=path.join(dir,'deck-project.json');
assert(saveProject(file,createAuthoredProject(semanticFixture()),null).ok);
const project=loadProject(file);renderProject(project,path.join(dir,'index.html'));
const server=await createFusionServer({dir});
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1920,height:1080}});
 await page.goto(`http://127.0.0.1:${server.address().port}/index.html`);
 await page.waitForFunction(()=>window.__fusionEditor);await page.evaluate(()=>window.__fusionEditor.ready());
 const qa=await measureProject(null,project,{page,screenshotDir:path.join(dir,'screens')});assert(qa.ok,JSON.stringify(qa));
 const html=await page.evaluate(()=>window.__fusionEditor.serializeHtml());assert(validatePortableHtml(html).ok);
 const exported=extractPortableProject(html);assert.deepEqual(exported.contentPlan,project.contentPlan);
 const offlinePath=path.join(dir,'candidate.html');fs.writeFileSync(offlinePath,html);
 const context=await browser.newContext({offline:true});const offline=await context.newPage();await offline.goto(pathToFileURL(offlinePath).href);
 await offline.waitForFunction(()=>window.__fusionEditor);await offline.evaluate(()=>window.__fusionEditor.ready());
 await offline.evaluate(()=>window.__fusionEditor.apply({type:'text',slideId:'p1',elementId:'ea',text:'人工修改核对步骤'}));
 const edited=await offline.evaluate(()=>window.__fusionEditor.getProject());assert(checkCoverage(edited).some(i=>i.kind==='bound-content-needs-reconciliation'));
 await offline.evaluate(()=>window.__fusionEditor.undo());assert.deepEqual(checkCoverage(await offline.evaluate(()=>window.__fusionEditor.getProject())),[]);
 await offline.evaluate(()=>window.__fusionEditor.redo());
 await offline.locator('#deck > .active [data-fusion-element="ea"]').fill('人工修改核对步骤（二）');
 const changed=await offline.evaluate(()=>window.__fusionEditor.serializeHtml());const snapshot=extractPortableProject(changed);assert.equal(snapshot.slides[0].elements[0].text,'人工修改核对步骤（二）');assert.deepEqual(snapshot.contentPlan.slides[0].regions,project.contentPlan.slides[0].regions);
 fs.writeFileSync(path.join(dir,'edited.html'),changed);await offline.goto(pathToFileURL(path.join(dir,'edited.html')).href);await offline.waitForFunction(()=>window.__fusionEditor);await offline.evaluate(()=>window.__fusionEditor.ready());
 assert.equal(await offline.locator('#deck > .active [data-fusion-element="ea"]').innerText(),'人工修改核对步骤（二）');
 assert(checkCoverage(await offline.evaluate(()=>window.__fusionEditor.getProject())).some(i=>i.kind==='bound-content-needs-reconciliation'));
 console.log(JSON.stringify({ok:true,scope:'contract/render/offline-save-reopen',aestheticAcceptance:'not-reviewed',pages:qa.pages.length}));
} finally {server.closeAllConnections();await new Promise(r=>server.close(r));await browser.close();}
